"""Bounded opaque image/feature storage for exact two-pass CED on stage A."""
from collections import OrderedDict
from contextlib import contextmanager
from dataclasses import asdict
import hashlib
import os
from pathlib import Path
import re
import shutil
import sqlite3
import threading
import time
import uuid

import numpy as np

from .jsonutil import ValidationError, canonical, integer, loads
from .protocol import hex_id
from .vision_input import ImageInfo, MAX_IMAGE_BYTES, inspect_image

_CHUNK = 1024 * 1024
_OWNER = b"DeepSeekRPC opaque image cache v1\n"


class ImageAssets:
    """One process owns this dedicated directory; requests pin their image IDs.

    Originals are retained independently of feature eviction. Features are exact
    BF16 rows from the actual owned vision graph, never a reduced substitute.
    No caller-supplied path or filename is accepted. Disk and RAM bytes/entries
    have explicit bounds; a request larger than them fails admission.
    """
    def __init__(self, root: Path, *, identity, disk_bytes=64 * 1024 ** 3,
                 ram_bytes=64 * 1024 ** 2, max_entries=4096):
        hex_id(identity, 64, "image asset model/runtime identity")
        self.identity = identity
        self.disk_bytes = integer(disk_bytes, "image disk byte budget", 1, 1024 ** 4)
        self.ram_bytes = integer(ram_bytes, "image RAM byte budget", 0, 1024 ** 3)
        self.max_entries = integer(max_entries, "image asset entry budget", 1, 8192)
        root.mkdir(parents=True, exist_ok=True)
        self.root = root.resolve(strict=True)
        owner = self.root / ".owner"
        if not owner.exists():
            if next(self.root.iterdir(), None) is not None:
                raise ValidationError("image cache requires its own empty directory or existing ownership marker")
            owner.write_bytes(_OWNER)
        if owner.is_symlink() or owner.stat().st_size != len(_OWNER) or owner.read_bytes() != _OWNER:
            raise ValidationError("image cache ownership marker is invalid")
        database = self.root / "assets.sqlite"
        for name in ("assets.sqlite", "assets.sqlite-wal", "assets.sqlite-shm", "assets.sqlite-journal"):
            path = self.root / name
            if path.is_symlink():
                raise ValidationError("image cache database must not be a redirected file")
            if path.exists() and path.stat().st_size > self.max_entries * 16384 + 8 * 1024 ** 2:
                raise ValidationError("image cache database exceeds its admitted metadata inventory")
        self._db = sqlite3.connect(database, check_same_thread=False, timeout=5)
        self._db.setlimit(sqlite3.SQLITE_LIMIT_LENGTH, 16384)
        self._db.execute("PRAGMA cache_size=-2048")
        self._db.execute("PRAGMA journal_mode=WAL")
        self._db.execute("PRAGMA synchronous=FULL")
        self._db.execute("CREATE TABLE IF NOT EXISTS images (key TEXT PRIMARY KEY, info BLOB NOT NULL, "
                         "feature_sha TEXT, feature_bytes INTEGER NOT NULL DEFAULT 0, touched INTEGER NOT NULL)")
        self._db.commit()
        count, = self._db.execute("SELECT COUNT(*) FROM images").fetchone()
        if count > self.max_entries:
            self._db.close()
            raise ValidationError("existing image cache exceeds its admitted entry budget")
        self._lock, self._pins = threading.RLock(), {}
        self._ram, self._ram_used, self._verified = OrderedDict(), 0, OrderedDict()
        self._closed = False
        # A crash may leave only files generated by our atomic writer. Clean
        # those known opaque orphans without adopting arbitrary directory data.
        known = {row[0]: (ImageInfo.from_wire(loads(row[1], limit=4096)), row[2], row[3])
                 for row in self._db.execute("SELECT key, info, feature_sha, feature_bytes FROM images")}
        self.used = sum(info.original_bytes + size for info, _, size in known.values())
        for key, (info, digest, size) in known.items():
            if key != info.key or size not in (0, info.span_tokens * 5120 * 2) or (digest is None) != (size == 0):
                raise ValidationError("existing image cache metadata is inconsistent")
        for index, path in enumerate(self.root.iterdir()):
            if index >= 4 * self.max_entries + 16:
                raise ValidationError("image cache directory exceeds its bounded generated inventory")
            if path.name in {".owner", "assets.sqlite", "assets.sqlite-wal", "assets.sqlite-shm", "assets.sqlite-journal"}:
                continue
            match = re.fullmatch(r"([a-f0-9]{64})\.(img|bf16)", path.name)
            temporary = re.fullmatch(r"tmp-[a-f0-9]{32}", path.name)
            if path.is_symlink() or not path.is_file() or not (match or temporary):
                raise ValidationError("image cache contains a non-generated or redirected entry")
            if temporary or match[1] not in known or match[2] == "bf16" and known[match[1]][1] is None:
                path.unlink()
        self._admit(0)

    def _path(self, key, suffix):
        hex_id(key, 64, "opaque image asset")
        if suffix not in {"img", "bf16"}:
            raise ValidationError("unknown image asset file type")
        path = self.root / f"{key}.{suffix}"
        if path.is_symlink() or path.resolve().parent != self.root:
            raise ValidationError("image asset escapes its dedicated cache directory")
        return path

    def _row(self, key):
        if self._closed:
            raise ConnectionError("image asset store is closed")
        hex_id(key, 64, "opaque image asset")
        row = self._db.execute("SELECT info, feature_sha, feature_bytes FROM images WHERE key=?", (key,)).fetchone()
        if row is None:
            raise ValidationError("original image asset is no longer available; resubmit the original image")
        info = ImageInfo.from_wire(loads(row[0], limit=4096))
        if info.key != key or info.identity != self.identity:
            raise ValidationError("image asset belongs to a different original image or model/runtime identity")
        return info, row[1], row[2]

    def _forget_ram(self, key):
        data = self._ram.pop(key, None)
        if data is not None:
            self._ram_used -= len(data)
        self._verified.pop(key, None)

    def _admit(self, required, *, protect=None, entry=False):
        count, = self._db.execute("SELECT COUNT(*) FROM images").fetchone()
        while self.used + required > self.disk_bytes or entry and count >= self.max_entries:
            candidates = self._db.execute("SELECT key, info, feature_bytes FROM images ORDER BY touched, key")
            victim = next((row for row in candidates if not self._pins.get(row[0]) and row[0] != protect), None)
            if victim is None:
                raise ValidationError("pinned image assets exceed the admitted disk/entry budget")
            key, raw, size = victim
            info = ImageInfo.from_wire(loads(raw, limit=4096))
            for suffix in ("img", "bf16"):
                self._path(key, suffix).unlink(missing_ok=True)
            self._db.execute("DELETE FROM images WHERE key=?", (key,))
            self._db.commit()
            self.used -= info.original_bytes + size
            count -= 1
            self._forget_ram(key)
        if required and shutil.disk_usage(self.root).free < required + 64 * 1024 ** 2:
            raise ValidationError("image cache volume lacks space for the bounded atomic write and reserve")

    def _atomic(self, destination, data):
        temporary = self.root / f"tmp-{uuid.uuid4().hex}"
        try:
            with temporary.open("xb") as stream:
                view = memoryview(data)
                for offset in range(0, len(view), _CHUNK):
                    stream.write(view[offset:offset + _CHUNK])
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temporary, destination)
        finally:
            temporary.unlink(missing_ok=True)

    def ingest(self, original: bytes):
        info = inspect_image(original, identity=self.identity)
        with self._lock:
            if self._closed:
                raise ConnectionError("image asset store is closed")
            existing = self._db.execute("SELECT key FROM images WHERE key=?", (info.key,)).fetchone()
            if existing is not None:
                self.original(info.key)  # Revalidate an existing original before claiming a hit.
                return info
            self._admit(len(original), protect=info.key, entry=True)
            self._atomic(self._path(info.key, "img"), original)
            try:
                self._db.execute("INSERT INTO images (key, info, touched) VALUES (?, ?, ?)",
                                 (info.key, canonical(asdict(info)), time.time_ns()))
                self._db.commit()
            except BaseException:
                self._db.rollback()
                self._path(info.key, "img").unlink(missing_ok=True)
                raise
            self.used += len(original)
        return info

    @contextmanager
    def pin(self, keys):
        keys = tuple(keys)
        if len(keys) > 4096 or any(not isinstance(k, str) for k in keys):
            raise ValidationError("image request pins exceed the bounded original image inventory")
        with self._lock:
            for key in keys:
                self._row(key)
            for key in keys:
                self._pins[key] = self._pins.get(key, 0) + 1
        try:
            yield
        finally:
            with self._lock:
                for key in keys:
                    self._pins[key] -= 1
                    if not self._pins[key]:
                        del self._pins[key]

    def info(self, key):
        with self._lock:
            return self._row(key)[0]

    def original(self, key):
        with self._lock:
            info, _, _ = self._row(key)
            with self._path(key, "img").open("rb") as stream:
                data = stream.read(MAX_IMAGE_BYTES + 1)
            if len(data) != info.original_bytes or hashlib.sha256(data).hexdigest() != info.original_sha256:
                raise ValidationError("original image asset checksum/length changed")
            return data

    def has_features(self, key):
        with self._lock:
            _, digest, _ = self._row(key)
            return digest is not None

    def store_features(self, key, bf16_bytes):
        with self._lock:
            info, digest, size = self._row(key)
            expected = info.span_tokens * 5120 * 2
            if not isinstance(bf16_bytes, bytes) or len(bf16_bytes) != expected:
                raise ValidationError("vision feature bytes differ from the exact BF16 span geometry")
            bits = np.frombuffer(bf16_bytes, dtype="<u2")
            if np.any((bits & 0x7f80) == 0x7f80):
                raise ValidationError("vision features contain nonfinite BF16 values")
            checksum = hashlib.sha256(bf16_bytes).hexdigest()
            if digest is not None:
                if digest != checksum or size != expected:
                    raise ValidationError("recomputed original vision features differ from the cached exact rows")
                self.read_rows(key, 0, 1)
                return
            self._admit(expected, protect=key)
            self._atomic(self._path(key, "bf16"), bf16_bytes)
            try:
                self._db.execute("UPDATE images SET feature_sha=?, feature_bytes=?, touched=? WHERE key=?",
                                 (checksum, expected, time.time_ns(), key))
                self._db.commit()
            except BaseException:
                self._db.rollback()
                self._path(key, "bf16").unlink(missing_ok=True)
                raise
            self.used += expected

    @staticmethod
    def _signature(stat):
        return stat.st_dev, stat.st_ino, stat.st_size, stat.st_mtime_ns, stat.st_ctime_ns

    def read_rows(self, key, start, rows):
        with self._lock:
            info, digest, size = self._row(key)
            integer(start, "image feature row start", 0, info.span_tokens - 1)
            integer(rows, "bounded image feature rows", 1, min(64, info.span_tokens - start))
            if digest is None:
                raise ValidationError("original image has no computed vision features")
            offset, length = start * 10240, rows * 10240
            data = self._ram.get(key)
            if data is not None:
                self._ram.move_to_end(key)
                return data[offset:offset + length]
            path = self._path(key, "bf16")
            with path.open("rb") as stream:
                before = self._signature(os.fstat(stream.fileno()))
                if before[2] != size:
                    raise ValidationError("cached vision feature length changed")
                if self._verified.get(key) != before:
                    hasher = hashlib.sha256()
                    remaining = size
                    while remaining:
                        chunk = stream.read(min(_CHUNK, remaining))
                        if not chunk:
                            raise ValidationError("cached vision features ended before their admitted length")
                        hasher.update(chunk)
                        remaining -= len(chunk)
                    if hasher.hexdigest() != digest or self._signature(os.fstat(stream.fileno())) != before:
                        raise ValidationError("cached vision feature checksum changed")
                    self._verified[key] = before
                    if len(self._verified) > self.max_entries:
                        self._verified.popitem(last=False)
                if size <= self.ram_bytes:
                    while self._ram and self._ram_used + size > self.ram_bytes:
                        _, evicted = self._ram.popitem(last=False)
                        self._ram_used -= len(evicted)
                    stream.seek(0)
                    data = stream.read(size + 1)
                    if len(data) != size or self._signature(os.fstat(stream.fileno())) != before:
                        raise ValidationError("cached vision features changed during the RAM copy")
                    self._ram[key] = data
                    self._ram_used += size
                    result = data[offset:offset + length]
                else:
                    stream.seek(offset)
                    result = stream.read(length)
                    if len(result) != length or self._signature(os.fstat(stream.fileno())) != before:
                        raise ValidationError("cached vision feature tile changed during the read")
            self._db.execute("UPDATE images SET touched=? WHERE key=?", (time.time_ns(), key))
            self._db.commit()
            return result

    def close(self):
        with self._lock:
            if self._pins:
                raise ValidationError("image assets still belong to an active request")
            if not self._closed:
                self._db.close()
                self._ram.clear()
                self._ram_used = 0
                self._closed = True
